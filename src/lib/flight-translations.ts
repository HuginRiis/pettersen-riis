export function translateAirline(codeOrCallsign: string | null | undefined): string | null {
  if (!codeOrCallsign) return null;
  const s = codeOrCallsign.trim().toUpperCase().replace(/\s+/g, "");
  if (!s) return null;
  // Hvis det er et helt callsign (f.eks. "SAS4471"), trekk ut 3-bokstavs prefiks.
  const m = s.match(/^([A-Z]{3})\d/);
  const key = m ? m[1] : s.slice(0, 3);
  return AIRLINES[key] ?? null;
}

